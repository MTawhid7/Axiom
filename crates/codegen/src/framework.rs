//! Running generators: writing their outputs, or checking that the
//! committed outputs are fresh.

use std::fmt;
use std::io::{self, Write as _};
use std::path::{Path, PathBuf};
use std::process::Stdio;

/// One generator: it reads its inputs under the repository's root and
/// returns its outputs.
pub trait Generator {
    /// The generator's name, as headers and `--list` show it.
    fn name(&self) -> &'static str;
    /// Its inputs, relative to the repository's root.
    fn inputs(&self) -> &[&'static str];
    /// Its outputs, unformatted and without their header.
    fn generate(&self, root: &Path) -> Result<Vec<Output>, Error>;
}

/// A generated file: where it goes, relative to the repository's root, and
/// its Rust source.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Output {
    /// The file's path, under a crate's `src/generated/`.
    pub path: PathBuf,
    /// The Rust source, before formatting.
    pub source: String,
}

/// Why generation failed.
#[derive(Debug)]
pub enum Error {
    /// An input couldn't be read, or an output written.
    Io(PathBuf, io::Error),
    /// An input is malformed: the file, a line and what is wrong.
    Input(PathBuf, usize, String),
    /// An output would land outside a crate's `src/generated/`.
    Placement(PathBuf),
    /// rustfmt failed on an output, which means the generator emitted
    /// invalid Rust.
    Format(PathBuf, String),
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Io(path, error) => write!(f, "{}: {error}", path.display()),
            Self::Input(path, line, what) => write!(f, "{}:{line}: {what}", path.display()),
            Self::Placement(path) => write!(
                f,
                "{}: outputs go under a crate's src/generated/",
                path.display()
            ),
            Self::Format(path, stderr) => write!(
                f,
                "{}: rustfmt refused the output:\n{stderr}",
                path.display()
            ),
        }
    }
}

impl std::error::Error for Error {}

/// A committed output that differs from what its generator now produces.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Stale {
    /// The output's path, relative to the repository's root.
    pub path: PathBuf,
    /// Whether the committed file is missing altogether.
    pub missing: bool,
}

/// The header every output begins with (invariant 2).
#[must_use]
pub fn header(generator: &str, inputs: &[&str]) -> String {
    format!(
        "// @generated by codegen's {generator} generator from {}.\n// Don't edit: change the input and run `cargo run -p codegen` (ES19).\n\n",
        inputs.join(", ")
    )
}

/// Every generator's outputs, with their headers, formatted.
fn render(root: &Path, generators: &[Box<dyn Generator>]) -> Result<Vec<Output>, Error> {
    let mut rendered = Vec::new();
    for generator in generators {
        for output in generator.generate(root)? {
            if !is_generated_path(&output.path) {
                return Err(Error::Placement(output.path));
            }
            let source = format!(
                "{}{}",
                header(generator.name(), generator.inputs()),
                output.source
            );
            let source = rustfmt(root, &output.path, &source)?;
            rendered.push(Output {
                path: output.path,
                source,
            });
        }
    }
    Ok(rendered)
}

/// Whether `path` is `crates/<crate>/src/generated/…` (invariant 3).
fn is_generated_path(path: &Path) -> bool {
    let parts: Vec<_> = path
        .components()
        .map(|c| c.as_os_str().to_string_lossy())
        .collect();
    matches!(parts.as_slice(), [crates, _, src, generated, _, ..]
        if crates == "crates" && src == "src" && generated == "generated")
}

/// Formats `source` with the toolchain's rustfmt and the repository's
/// `rustfmt.toml`, as `cargo fmt` would format the committed file.
#[expect(
    clippy::disallowed_types,
    reason = "ES13: codegen is a build tool, and formats its outputs with rustfmt"
)]
fn rustfmt(root: &Path, path: &Path, source: &str) -> Result<String, Error> {
    let io_error = |error| Error::Io(path.to_path_buf(), error);
    let mut child = std::process::Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--config-path"])
        .arg(root.join("rustfmt.toml"))
        .current_dir(root)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(io_error)?;
    if let Some(mut stdin) = child.stdin.take() {
        stdin.write_all(source.as_bytes()).map_err(io_error)?;
    }
    let result = child.wait_with_output().map_err(io_error)?;
    if !result.status.success() {
        return Err(Error::Format(
            path.to_path_buf(),
            String::from_utf8_lossy(&result.stderr).into_owned(),
        ));
    }
    String::from_utf8(result.stdout)
        .map_err(|error| Error::Format(path.to_path_buf(), error.to_string()))
}

/// Writes every output that differs from its file; returns the paths written.
#[expect(
    clippy::disallowed_methods,
    reason = "ES13: codegen is a build tool that writes its outputs"
)]
pub fn write(root: &Path, generators: &[Box<dyn Generator>]) -> Result<Vec<PathBuf>, Error> {
    let mut written = Vec::new();
    for output in render(root, generators)? {
        let path = root.join(&output.path);
        if std::fs::read_to_string(&path).ok().as_deref() == Some(output.source.as_str()) {
            continue;
        }
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent).map_err(|error| Error::Io(path.clone(), error))?;
        }
        std::fs::write(&path, &output.source).map_err(|error| Error::Io(path.clone(), error))?;
        written.push(output.path);
    }
    Ok(written)
}

/// The committed outputs that differ from what the generators produce now.
#[expect(
    clippy::disallowed_methods,
    reason = "ES13: codegen is a build tool that reads its committed outputs"
)]
pub fn check(root: &Path, generators: &[Box<dyn Generator>]) -> Result<Vec<Stale>, Error> {
    let mut stale = Vec::new();
    for output in render(root, generators)? {
        match std::fs::read_to_string(root.join(&output.path)) {
            Ok(committed) if committed == output.source => {}
            Ok(_) => stale.push(Stale {
                path: output.path,
                missing: false,
            }),
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                stale.push(Stale {
                    path: output.path,
                    missing: true,
                });
            }
            Err(error) => return Err(Error::Io(output.path, error)),
        }
    }
    Ok(stale)
}

/// Each generator's name, inputs and outputs, one line each.
pub fn list(root: &Path, generators: &[Box<dyn Generator>]) -> Result<Vec<String>, Error> {
    let mut lines = Vec::new();
    for generator in generators {
        let outputs: Vec<String> = generator
            .generate(root)?
            .into_iter()
            .map(|output| output.path.display().to_string())
            .collect();
        lines.push(format!(
            "{}: {} -> {}",
            generator.name(),
            generator.inputs().join(", "),
            outputs.join(", ")
        ));
    }
    Ok(lines)
}
