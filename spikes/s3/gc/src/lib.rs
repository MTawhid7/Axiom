/// Declare a heap: one [`Arena`] per object type, plus a [`HeapCore`].
///
/// ```ignore
/// heap! {
///     pub struct VmHeap {
///         objects: Object,
///         arrays: Array,
///     }
/// }
/// ```
///
/// The expansion contains:
/// - the struct `Name<'r, S: RootStack, B: Barrier = NoBarrier>`, with one
///   public `Arena` field per type and a `core: HeapCore<'r, S, B>`;
/// - `Allocated` impls, which number the arenas in field order (at most
///   [`MAX_ARENAS`]);
/// - `Store` and `HeapLayout` impls;
/// - `new(&roots, pacing)`, `alloc(value)` (never collects), and
///   `collect(&mut roots)`.
///
/// It expands to safe code only. Declare one heap per module.
#[macro_export]
macro_rules! heap {
    (
        $(#[$meta:meta])*
        $vis:vis struct $name:ident {
            $($field:ident : $ty:ty),+ $(,)?
        }
    ) => {
        $(#[$meta])*
        $vis struct $name<'r, S: $crate::RootStack, B: $crate::Barrier = $crate::NoBarrier> {
            $(pub $field: $crate::Arena<$ty>,)+
            pub core: $crate::HeapCore<'r, S, B>,
        }

        #[allow(non_camel_case_types, dead_code)]
        #[derive(Clone, Copy)]
        enum __S3ArenaIds {
            $($field,)+
            __Count,
        }

        const _: () = ::core::assert!(
            __S3ArenaIds::__Count as usize <= $crate::MAX_ARENAS,
            "a heap has at most MAX_ARENAS arenas"
        );

        $(
            impl $crate::Allocated for $ty {
                const ARENA: usize = __S3ArenaIds::$field as usize;
            }

            impl<'r, S: $crate::RootStack, B: $crate::Barrier> $crate::Store<$ty> for $name<'r, S, B> {
                #[inline]
                fn arena(&self) -> &$crate::Arena<$ty> {
                    &self.$field
                }
                #[inline]
                fn arena_mut(&mut self) -> &mut $crate::Arena<$ty> {
                    &mut self.$field
                }
            }
        )+

        impl<'r, S: $crate::RootStack, B: $crate::Barrier> $crate::HeapLayout<'r, S, B> for $name<'r, S, B> {
            fn arena_lens(&self) -> ::std::vec::Vec<usize> {
                ::std::vec![$(self.$field.len()),+]
            }

            fn mark_item(&self, arena: usize, index: usize, marker: &mut $crate::Marker) {
                $(
                    if arena == __S3ArenaIds::$field as usize {
                        return $crate::__mark_item(&self.$field, index, marker);
                    }
                )+
                ::core::unreachable!("unknown arena {arena}")
            }

            fn compact_all(&mut self, forwarding: &$crate::Forwarding) {
                $($crate::__compact(&mut self.$field, forwarding);)+
            }

            fn size(&self) -> (usize, usize) {
                (
                    0 $(+ self.$field.len())+,
                    0 $(+ self.$field.len() * ::core::mem::size_of::<$ty>())+,
                )
            }

            fn core(&mut self) -> &mut $crate::HeapCore<'r, S, B> {
                &mut self.core
            }
        }

        impl<'r, S: $crate::RootStack, B: $crate::Barrier> $name<'r, S, B> {
            /// An empty heap whose root frames use `roots`.
            $vis fn new(roots: &'r S, pacing: $crate::Pacing) -> Self {
                Self {
                    $($field: $crate::Arena::default(),)+
                    core: $crate::HeapCore::new(roots, pacing),
                }
            }

            /// Allocate without a safepoint: this never collects.
            #[inline]
            $vis fn alloc<T: $crate::Allocated>(&mut self, value: T) -> $crate::Handle<'static, T>
            where
                Self: $crate::Store<T>,
            {
                $crate::alloc(self, value)
            }

            /// A full collection, rooted at the root stack and at `roots`.
            $vis fn collect<R: $crate::Roots + ?Sized>(&mut self, roots: &mut R) {
                $crate::collect_heap(self, roots);
            }
        }
    };
}

/// Generate setters for handle-valued fields (ADR-0008 SH9, C3). Each setter
/// writes the field and calls the heap's [`Barrier::post_write`] for the
/// written object, so a barrier can later be added in one place.
///
/// ```ignore
/// setters! {
///     DomHeap.nodes: NodeData {
///         set_parent => parent: Option<NodeRef<'static>>,
///     }
/// }
/// // heap.set_parent(node, Some(parent));
/// ```
#[macro_export]
macro_rules! setters {
    (
        $heap:ident . $arena:ident : $ty:ty {
            $( $(#[$meta:meta])* $setter:ident => $field:ident : $fty:ty ),+ $(,)?
        }
    ) => {
        impl<'r, S: $crate::RootStack, B: $crate::Barrier> $heap<'r, S, B> {
            $(
                $(#[$meta])*
                #[inline]
                pub fn $setter(&mut self, object: $crate::Handle<'_, $ty>, value: $fty) {
                    let object = object.unbind();
                    self.$arena[object].$field = value;
                    self.core
                        .barrier
                        .post_write(<$ty as $crate::Allocated>::ARENA, object.index());
                }
            )+
        }
    };
}
