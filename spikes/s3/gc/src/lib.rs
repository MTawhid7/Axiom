//! # Spike S3: Pattern B's heap, with interchangeable root stacks
//!
//! A copy of S1's Pattern B heap (`s1-b-gc`, which stays untouched as the
//! baseline), changed in four ways for spike S3:
//! - **Values.** [`Value`] is a NaN-boxed 64-bit value with `u32` handles
//!   inside (ADR-0008 SH13). Arenas, registers and root slots hold values,
//!   and the collector marks and relocates them.
//! - **Root stacks behind one trait** ([`RootStack`]), for S3-Q1: S1's
//!   `RefCell` design ([`RefCellStack`]); a safe stack of `Cell` chunks
//!   ([`CellStack`]); S3's first C1 stack ([`RawStack`], the only `unsafe`, in
//!   `src/raw/`, archived at Gate C); and C1's stack, a safe contiguous array
//!   borrowed from a zeroed buffer ([`SliceStack`], with its field-order
//!   control [`SliceStackLenLast`]). Heaps, frames and scoped handles are
//!   generic over the stack.
//! - **The root stack lives outside the heap.** [`HeapCore`] borrows it for
//!   `'r`, and frames borrow it too, so they need no reference counting.
//! - **A write-barrier hook** ([`Barrier`]) for S3-Q5: setters generated by
//!   [`setters!`] call it; [`NoBarrier`] is free and [`CardBarrier`] marks
//!   cards.
//!
//! Everything else is S1's: typed arenas, scope tokens, safe `Trace`, and a
//! stop-the-world mark–compact collector with rank-based forwarding.
//!
//! ```
//! use s3_gc::{heap, slot_buffer, Forwarding, Handle, Marker, Pacing, Roots, SliceStack, Trace};
//!
//! struct Node { next: Option<Handle<'static, Node>>, value: u32 }
//! heap! { struct Heap { nodes: Node } }
//! impl Trace for Node {
//!     fn mark(&self, m: &mut Marker) { m.mark_opt(self.next) }
//!     fn relocate(&mut self, f: &Forwarding) { f.relocate_opt(&mut self.next) }
//! }
//! struct Globals { root: Option<Handle<'static, Node>> }
//! impl Roots for Globals {
//!     fn mark(&self, m: &mut Marker) { m.mark_opt(self.root) }
//!     fn relocate(&mut self, f: &Forwarding) { f.relocate_opt(&mut self.root) }
//! }
//!
//! let mut buffer = slot_buffer(1024);
//! let stack = SliceStack::new(&mut buffer);
//! let mut heap: Heap<'_, SliceStack<'_>> = Heap::new(&stack, Pacing::default());
//! let mut globals = Globals { root: None };
//! let a = heap.alloc(Node { next: None, value: 1 });
//! let b = heap.alloc(Node { next: Some(a), value: 2 });
//! heap.nodes[a].next = Some(b); // a ⇄ b: a cycle
//! heap.alloc(Node { next: None, value: 3 }); // garbage
//! globals.root = Some(a);
//!
//! heap.collect(&mut globals);
//! assert_eq!(heap.nodes.len(), 2, "a reachable cycle survives; garbage is compacted away");
//! let a = globals.root.unwrap(); // the collector relocated the root
//! assert_eq!(heap.nodes[heap.nodes[a].next.unwrap()].value, 2);
//!
//! // A rooted handle survives a collection, relocated.
//! let frame = heap.core.frame();
//! let rooted = a.scope(&frame);
//! globals.root = None;
//! heap.collect(&mut globals);
//! assert_eq!(heap.nodes[heap.nodes[rooted.get()].next.unwrap()].value, 2);
//! drop(frame);
//! heap.collect(&mut globals);
//! assert!(heap.nodes.is_empty(), "an unreachable cycle is reclaimed");
//! ```
//!
//! # Safety model
//!
//! Only `src/raw/` contains `unsafe`: the allocation behind the archived
//! [`RawStack`], under invariants R1–R3, checked by Miri. C1's stack,
//! [`SliceStack`], needs none. Everything else, including what
//! the macros expand to, is safe. As in S1, a GC bug is a stale index, a
//! logic error, never undefined behaviour. Debug builds catch stale handles
//! and values by their collection epoch.
//!
//! A rooted handle cannot outlive its frame:
//!
//! ```compile_fail,E0597
//! # use s3_gc::{heap, CellStack, Forwarding, Marker, Pacing, Trace};
//! # struct Node;
//! # heap! { struct Heap { nodes: Node } }
//! # impl Trace for Node { fn mark(&self, _: &mut Marker) {} fn relocate(&mut self, _: &Forwarding) {} }
//! let stack = CellStack::default();
//! let mut heap: Heap<'_, CellStack> = Heap::new(&stack, Pacing::default());
//! let node = heap.alloc(Node);
//! let rooted = {
//!     let frame = heap.core.frame();
//!     node.scope(&frame)
//! };
//! let _ = rooted.get();
//! ```
#![deny(unsafe_code)]

